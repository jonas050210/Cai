"""Collect permissively licensed source code from GitHub into JSONL records.

Only repositories whose GitHub license is on an explicit allow-list are used.
Downloads are tarballs (no git history), files are filtered by extension, size
and path, and everything is written as records compatible with
``codeplan-prepare``. A manifest with checksums keeps the corpus auditable.

This tool needs network access. Set ``GITHUB_TOKEN`` to raise the API rate
limit (unauthenticated requests are limited to 60/hour).
"""

from __future__ import annotations

import argparse
import fnmatch
import hashlib
import http.client
import io
import json
import os
import tarfile
import time
import urllib.error
import urllib.parse
import urllib.request
import zlib
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
from typing import Any, Iterable, Iterator

from .ingest import CODE_EXTS, TEXT_EXTS, guess_domain, guess_lang

API_ROOT = "https://api.github.com"

# SPDX ids we accept. Extend deliberately, not casually.
ALLOWED_LICENSES = {
    "mit",
    "apache-2.0",
    "bsd-2-clause",
    "bsd-3-clause",
    "isc",
    "cc0-1.0",
    "unlicense",
    "mpl-2.0",
    # Wikipedia text is CC BY-SA 4.0; attribution stays in the record's source
    "cc-by-sa-4.0",
}

SKIP_DIR_PARTS = {
    ".git", ".github", ".venv", "venv", "env", "node_modules", "__pycache__",
    "third_party", "third-party", "vendor", "vendored", "dist", "build",
    "site-packages", ".mypy_cache", ".pytest_cache", "coverage", "migrations",
}

SKIP_PATTERNS = [
    "*.min.js", "*.min.css", "*.map", "*.lock", "*-lock.json", "*.lock.json",
    "*.snap", "*.svg", "*.png", "*.jpg", "*.jpeg", "*.gif", "*.ico", "*.pdf",
    "*.woff", "*.woff2", "*.ttf", "*.eot", "*.mp4", "*.zip", "*.tar", "*.gz",
    "*.pb", "*.bin", "*.onnx", "*.ipynb", "*.po", "*.pot", "*.csv",
]

GENERATED_MARKERS = (
    "code generated by",
    "do not edit",
    "autogenerated",
    "auto-generated",
    "@generated",
)


TOKEN_FILE = Path.home() / ".config" / "codeplan" / "env"


def load_token(explicit: str | None = None) -> str | None:
    """Token from --token, GITHUB_TOKEN, or ~/.config/codeplan/env (in that order)."""
    if explicit:
        return explicit
    env = os.environ.get("GITHUB_TOKEN")
    if env:
        return env.strip()
    if TOKEN_FILE.exists():
        for line in TOKEN_FILE.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            for prefix in ("export GITHUB_TOKEN=", "GITHUB_TOKEN="):
                if line.startswith(prefix):
                    return line[len(prefix):].strip().strip('"').strip("'")
    return None


def token_warning(token: str | None) -> str | None:
    """Catch the most common copy/paste mistakes before 18 requests fail."""
    if not token:
        return None
    if token.startswith("ghp_ghp_") or token.startswith("github_pat_github_pat_"):
        return (
            "the token starts with a doubled prefix (ghp_ghp_...). Paste only the "
            "part GitHub shows you."
        )
    if token.startswith("ghp_") and len(token) != 40:
        return f"a classic token is 40 characters, this one has {len(token)} (truncated or doubled?)"
    if token.startswith("github_pat_") and len(token) < 80:
        return f"a fine-grained token is longer than {len(token)} characters"
    return None


def license_ok(spdx: str | None) -> bool:
    return bool(spdx) and spdx.lower() in ALLOWED_LICENSES


def should_skip_path(path: str) -> bool:
    parts = [p for p in path.replace("\\", "/").split("/") if p]
    if not parts:
        return True
    if any(part.lower() in SKIP_DIR_PARTS for part in parts[:-1]):
        return True
    name = parts[-1].lower()
    if name.startswith(".") or name.startswith("test_") or name.endswith("_test.py"):
        return True
    return any(fnmatch.fnmatch(name, pattern) for pattern in SKIP_PATTERNS)


def decode_text(raw: bytes) -> str | None:
    if b"\x00" in raw[:4096]:
        return None
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        return None
    head = text[:400].lower()
    if any(marker in head for marker in GENERATED_MARKERS):
        return None
    return text


def iter_repo_files(
    members: Iterable[tuple[str, bytes]], max_file_bytes: int = 120_000
) -> Iterator[tuple[str, str]]:
    """Yield ``(path, text)`` for files worth keeping from a repository tarball."""
    for path, raw in members:
        if len(raw) < 200 or len(raw) > max_file_bytes:
            continue
        if should_skip_path(path):
            continue
        suffix = Path(path).suffix.lower()
        if suffix not in CODE_EXTS | TEXT_EXTS:
            continue
        text = decode_text(raw)
        if text is None or len(text.strip()) < 200:
            continue
        yield path, text


def records_from_files(
    repo: str, spdx: str, files: Iterable[tuple[str, bytes]], source_prefix: str = "github"
) -> list[dict]:
    records = []
    for path, text in iter_repo_files(files):
        digest = hashlib.sha256(f"{repo}:{path}".encode()).hexdigest()[:16]
        records.append(
            {
                "id": digest,
                "text": text,
                "lang": guess_lang(text),
                "domain": guess_domain(Path(path), text),
                "license": spdx,
                "source": f"{source_prefix}:{repo}/{path}",
            }
        )
    return records


def _request(url: str, token: str | None, accept: str = "application/vnd.github+json") -> bytes:
    headers = {"User-Agent": "codeplan-collect", "Accept": accept}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    request = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(request, timeout=120) as response:
        return response.read()


TRANSIENT_ERRORS = (
    http.client.IncompleteRead,
    http.client.BadStatusLine,
    ConnectionResetError,
    ConnectionAbortedError,
    TimeoutError,
    urllib.error.URLError,
)


def _download(url: str, token: str | None, max_bytes: int, attempts: int = 3) -> bytes:
    """Stream a download and abort before it gets too large for memory.

    Home connections drop large transfers; a truncated chunked response raises
    ``IncompleteRead``. Retry a few times with backoff before giving up, so one
    flaky repo cannot end a 470-repository overnight run.
    """
    headers = {"User-Agent": "codeplan-collect", "Accept": "application/vnd.github+json"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    last_error: Exception | None = None
    for attempt in range(attempts):
        request = urllib.request.Request(url, headers=headers)
        chunks = []
        total = 0
        try:
            with urllib.request.urlopen(request, timeout=180) as response:
                while True:
                    chunk = response.read(1 << 20)
                    if not chunk:
                        break
                    total += len(chunk)
                    if total > max_bytes:
                        raise ValueError(
                            f"tarball exceeds {max_bytes / 1e6:.0f} MB limit"
                        )
                    chunks.append(chunk)
            return b"".join(chunks)
        except ValueError:
            raise  # too large is not transient
        except TRANSIENT_ERRORS as exc:
            last_error = exc
            if attempt + 1 < attempts:
                time.sleep(2 * (attempt + 1))
    assert last_error is not None
    raise last_error


def search_repos(
    language: str,
    spdx: str,
    min_stars: int,
    per_page: int,
    max_repos: int,
    token: str | None,
    sleep: float,
) -> list[dict]:
    query = f"language:{language} license:{spdx} stars:>={min_stars} archived:false"
    found: list[dict] = []
    page = 1
    while len(found) < max_repos:
        url = (
            f"{API_ROOT}/search/repositories?q={urllib.parse.quote(query)}"
            f"&sort=stars&order=desc&per_page={min(100, per_page)}&page={page}"
        )
        try:
            payload = json.loads(_request(url, token))
        except urllib.error.HTTPError as exc:
            print(f"  search failed ({exc.code}) for {query}; stopping this query")
            break
        items = payload.get("items", [])
        if not items:
            break
        for item in items:
            lic = (item.get("license") or {}).get("spdx_id")
            if not license_ok(lic):
                continue
            found.append(
                {
                    "full_name": item["full_name"],
                    "license": lic.lower(),
                    "stars": item.get("stargazers_count", 0),
                    "size_kb": item.get("size", 0),
                    "branch": item.get("default_branch", "main"),
                    "language": item.get("language"),
                }
            )
            if len(found) >= max_repos:
                break
        if len(items) < min(100, per_page):
            break
        page += 1
        time.sleep(sleep)
    return found


def repo_info(full_name: str, token: str | None) -> dict:
    """Fetch metadata for one repository (used when repos are given explicitly)."""
    payload = json.loads(_request(f"{API_ROOT}/repos/{full_name}", token))
    license_name = (payload.get("license") or {}).get("spdx_id")
    return {
        "full_name": payload["full_name"],
        "license": (license_name or "").lower(),
        "stars": payload.get("stargazers_count", 0),
        "size_kb": payload.get("size", 0),
        "branch": payload.get("default_branch", "main"),
        "language": payload.get("language"),
    }


def fetch_candidates(
    repos: list[str], token: str | None, sleep: float, workers: int
) -> tuple[list[dict], list[str], int]:
    """Look up repository metadata, in parallel when workers > 1.

    Returns ``(candidates, rejected, unauthorized_count)``. Rejected entries keep
    the reason so the caller can report them.
    """
    candidates: list[dict] = []
    rejected: list[str] = []
    unauthorized = 0

    def one(full_name: str) -> tuple[str, Any]:
        for attempt in range(3):
            try:
                return full_name, repo_info(full_name, token)
            except urllib.error.HTTPError as exc:
                if exc.code >= 500 and attempt < 2:
                    time.sleep(2 * (attempt + 1))
                    continue
                return full_name, exc
            except (*TRANSIENT_ERRORS, ValueError) as exc:
                if attempt < 2:
                    time.sleep(2 * (attempt + 1))
                    continue
                return full_name, exc
        return full_name, RuntimeError(f"{full_name}: metadata lookup failed")

    if workers <= 1:
        results = ((name, one(name)[1], 0) for name in repos)
        for name, info, _ in results:
            if isinstance(info, Exception):
                unauthorized += _report_lookup_error(name, info, rejected)
                continue
            if not license_ok(info["license"]):
                rejected.append(f"{name}: license {info['license'] or 'unknown'}")
                continue
            candidates.append(info)
            time.sleep(sleep)
        return candidates, rejected, unauthorized

    print(f"looking up {len(repos)} repositories with {workers} workers", flush=True)
    with ThreadPoolExecutor(max_workers=workers) as pool:
        futures = [pool.submit(one, name) for name in repos]
        for done, future in enumerate(as_completed(futures), start=1):
            if done % 25 == 0 or done == len(repos):
                print(f"  metadata {done}/{len(repos)}", flush=True)
            name, info = future.result()
            if isinstance(info, Exception):
                unauthorized += _report_lookup_error(name, info, rejected)
                continue
            if not license_ok(info["license"]):
                rejected.append(f"{name}: license {info['license'] or 'unknown'}")
                continue
            candidates.append(info)
    order = {name.lower(): i for i, name in enumerate(repos)}
    candidates.sort(key=lambda info: order.get(info["full_name"].lower(), 0))
    return candidates, rejected, unauthorized


def _report_lookup_error(name: str, exc: Exception, rejected: list[str]) -> int:
    if isinstance(exc, urllib.error.HTTPError):
        if exc.code == 401:
            return 1
        rejected.append(f"{name}: HTTP {exc.code}")
    else:
        rejected.append(f"{name}: {exc}")
    return 0


def download_records(
    repo: dict, token: str | None, max_repo_mb: float, attempts: int = 2
) -> tuple[list[dict], str, int]:
    """Download one repository and turn it into records (runs in a worker thread).

    A truncated body can also surface as ``tarfile.EOFError`` or a gzip/zlib
    error after a clean-looking download, so the whole download+unpack step is
    retried, not just the HTTP read.
    """
    last_error: Exception | None = None
    for attempt in range(attempts):
        try:
            members, digest = tarball_members(
                repo["full_name"], repo["branch"], token, max_repo_mb
            )
            return (
                records_from_files(repo["full_name"], repo["license"], members),
                digest,
                len(members),
            )
        except ValueError:
            raise  # too large is not transient
        except (tarfile.TarError, EOFError, OSError, zlib.error) as exc:
            last_error = exc
            if attempt + 1 < attempts:
                time.sleep(2 * (attempt + 1))
    assert last_error is not None
    raise last_error


def tarball_members(repo: str, branch: str, token: str | None, max_repo_mb: float):
    """Download a repository tarball and yield (relative path, bytes) members."""
    url = f"{API_ROOT}/repos/{repo}/tarball/{branch}"
    raw = _download(url, token, int(max_repo_mb * 1024 * 1024))
    digest = hashlib.sha256(raw).hexdigest()
    members = []
    with tarfile.open(fileobj=io.BytesIO(raw), mode="r:gz") as archive:
        for member in archive:
            if not member.isfile():
                continue
            # Drop the "<owner>-<repo>-<sha>/" prefix from the archive.
            parts = member.name.split("/", 1)
            if len(parts) != 2:
                continue
            handle = archive.extractfile(member)
            if handle is None:
                continue
            members.append((parts[1], handle.read()))
    return members, digest


def collect(
    out_path: Path,
    languages: list[str],
    licenses: list[str],
    min_stars: int,
    max_repos: int,
    max_repo_mb: float,
    token: str | None,
    sleep: float,
    dry_run: bool = False,
    repos: list[str] | None = None,
    min_size_kb: int = 100,
    min_records_per_repo: int = 5,
    workers: int = 1,
    fresh: bool = False,
) -> dict:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path = out_path.with_suffix(".manifest.jsonl")

    # Resume: repositories already recorded as "ok" are not downloaded again.
    # Records are appended, so an interrupted run never loses earlier work.
    done_repos: set[str] = set()
    if not fresh and manifest_path.exists():
        for line in manifest_path.read_text(encoding="utf-8").splitlines():
            try:
                entry = json.loads(line)
            except json.JSONDecodeError:
                continue
            if entry.get("status") == "ok":
                done_repos.add(entry.get("full_name", ""))
    if fresh:
        out_path.unlink(missing_ok=True)
        manifest_path.unlink(missing_ok=True)
    file_mode = "a" if out_path.exists() and out_path.stat().st_size else "w"
    manifest_mode = "a" if manifest_path.exists() else "w"
    seen_repos: set[str] = set()
    seen_text: set[str] = set()
    summary: dict[str, Any] = {
        "repos": 0, "records": 0, "chars": 0, "skipped": 0, "errors": 0,
        "already_done": len(done_repos), "workers": workers,
    }
    budget = max_repos

    if repos:
        candidates, rejected, unauthorized = fetch_candidates(
            repos, token, sleep, workers
        )
        for line in rejected:
            print(f"  {line}")
            summary["skipped"] += 1
        if unauthorized >= 3:
            raise SystemExit(
                "GitHub returned 401 Unauthorized three times: the token in "
                "GITHUB_TOKEN is invalid, expired or revoked.\n"
                "Create a new classic token without scopes and re-run."
            )
    else:
        candidates = []
        for license_name in licenses:
            if len(candidates) >= max_repos:
                break
            for language in languages:
                if len(candidates) >= max_repos:
                    break
                print(f"searching language={language} license={license_name}")
                remaining = max_repos - len(candidates)
                candidates.extend(
                    search_repos(
                        language, license_name, min_stars, remaining, remaining, token, sleep
                    )
                )

    # Decide what to download before starting any worker: keeps the budget,
    # the dry run and the manifest deterministic regardless of thread order.
    plan: list[dict] = []
    for repo in candidates:
        if budget <= 0:
            break
        name = repo["full_name"]
        if name in seen_repos or name in done_repos:
            continue
        seen_repos.add(name)
        budget -= 1
        if repo["size_kb"] < min_size_kb:
            plan.append({**repo, "_skip": "skipped-small"})
            continue
        # GitHub's size counts the whole history, tarballs are much smaller;
        # the real limit is enforced while streaming the download.
        if repo["size_kb"] > max_repo_mb * 1024 * 12:
            plan.append({**repo, "_skip": "skipped-huge"})
            continue
        plan.append(repo)

    with open(out_path, file_mode, encoding="utf-8") as out, open(
        manifest_path, manifest_mode, encoding="utf-8"
    ) as manifest:

        def skip(repo: dict, status: str, **extra: object) -> None:
            summary["skipped"] += 1
            clean = {k: v for k, v in repo.items() if not k.startswith("_")}
            manifest.write(
                json.dumps({**clean, **extra, "status": status}, ensure_ascii=False) + "\n"
            )
            if status != "ok":
                print(f"  {repo['full_name']}: {status}")

        def store(repo: dict, records: list[dict], digest: str, scanned: int) -> None:
            kept: list[dict] = []
            keys: list[str] = []
            for record in records:
                key = hashlib.sha256(record["text"].encode()).hexdigest()
                if key in seen_text:
                    continue
                keys.append(key)
                kept.append(record)
            if len(kept) < min_records_per_repo:
                skip(repo, "skipped-few-records", records=len(kept))
                return
            chars = 0
            for record, key in zip(kept, keys):
                seen_text.add(key)
                out.write(json.dumps(record, ensure_ascii=False) + "\n")
                chars += len(record["text"])
            summary["repos"] += 1
            summary["records"] += len(kept)
            summary["chars"] += chars
            clean = {k: v for k, v in repo.items() if not k.startswith("_")}
            manifest.write(
                json.dumps(
                    {
                        **clean,
                        "status": "ok",
                        "tarball_sha256": digest,
                        "files_scanned": scanned,
                        "records": len(kept),
                        "chars": chars,
                    },
                    ensure_ascii=False,
                )
                + "\n"
            )
            out.flush()
            manifest.flush()
            print(
                f"  {repo['full_name']}: {len(kept)} records, {chars / 1e3:.0f}k chars",
                flush=True,
            )

        pending = []
        for repo in plan:
            if repo.get("_skip"):
                skip(repo, repo["_skip"])
            elif dry_run:
                print(f"  would collect {repo['full_name']} "
                      f"({repo['license']}, {repo['stars']} stars)")
            else:
                pending.append(repo)

        if pending and not dry_run:
            if workers <= 1:
                for repo in pending:
                    try:
                        records, digest, scanned = download_records(repo, token, max_repo_mb)
                    except Exception as exc:  # one bad repo must not end the run
                        summary["errors"] += 1
                        skip(repo, "error", error=f"{type(exc).__name__}: {exc}")
                        time.sleep(sleep)
                        continue
                    store(repo, records, digest, scanned)
                    time.sleep(sleep)
            else:
                with ThreadPoolExecutor(max_workers=workers) as pool:
                    futures = {
                        pool.submit(download_records, repo, token, max_repo_mb): repo
                        for repo in pending
                    }
                    done = 0
                    for future in as_completed(futures):
                        repo = futures[future]
                        done += 1
                        try:
                            records, digest, scanned = future.result()
                        except Exception as exc:  # one bad repo must not end the run
                            summary["errors"] += 1
                            skip(repo, "error", error=f"{type(exc).__name__}: {exc}")
                            print(f"  {repo['full_name']}: {type(exc).__name__}, skipped")
                            continue
                        store(repo, records, digest, scanned)
                        print(f"  [{done}/{len(pending)}] {repo['full_name']}", flush=True)

    summary["manifest"] = str(manifest_path)
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description="Collect permissive GitHub code into JSONL.")
    parser.add_argument("--out", required=True, help="Output JSONL, e.g. data/raw/github.jsonl")
    parser.add_argument("--languages", default="python,typescript,javascript")
    parser.add_argument("--licenses", default=",".join(sorted(ALLOWED_LICENSES)))
    parser.add_argument("--min-stars", type=int, default=200)
    parser.add_argument("--max-repos", type=int, default=200)
    parser.add_argument("--max-repo-mb", type=float, default=40.0)
    parser.add_argument(
        "--workers",
        type=int,
        default=1,
        help="Parallel downloads (1 = sequential). 8-16 turns 470 repos into minutes",
    )
    parser.add_argument("--sleep", type=float, default=1.0, help="Seconds between API calls")
    parser.add_argument(
        "--token",
        default=None,
        help="GitHub token; defaults to $GITHUB_TOKEN or ~/.config/codeplan/env",
    )
    parser.add_argument("--dry-run", action="store_true", help="Only list repositories")
    parser.add_argument(
        "--fresh",
        action="store_true",
        help="Ignore an existing output/manifest and start over (default: resume)",
    )
    parser.add_argument("--repos", default=None, help="Comma separated owner/name list")
    parser.add_argument(
        "--repos-file",
        default=None,
        help="File with one owner/name per line (# starts a comment)",
    )
    parser.add_argument("--min-size-kb", type=int, default=100, help="Skip tiny repos")
    parser.add_argument(
        "--min-records-per-repo", type=int, default=5, help="Skip doc-only repositories"
    )
    args = parser.parse_args()
    args.token = load_token(args.token)

    repos = [v.strip() for v in (args.repos or "").split(",") if v.strip()]
    if args.repos_file:
        listed = Path(args.repos_file).read_text(encoding="utf-8").splitlines()
        repos.extend(
            line.split("#", 1)[0].strip() for line in listed
        )
        repos = [name for name in repos if name]

    # An explicit list is the budget: --max-repos defaults to 200 and used to
    # silently cut a 420-repository list down to its first 200 entries.
    if repos and args.max_repos == parser.get_default("max_repos"):
        args.max_repos = len(repos)

    if not args.token:
        print("Note: no GITHUB_TOKEN set; API limit is 60 requests/hour.")
    else:
        problem = token_warning(args.token)
        if problem:
            raise SystemExit(f"Refusing to use GITHUB_TOKEN: {problem}")

    languages = [v.strip() for v in args.languages.split(",") if v.strip()]
    licenses = [v.strip() for v in args.licenses.split(",") if v.strip()]
    unknown = [v for v in licenses if v.lower() not in ALLOWED_LICENSES]
    if unknown:
        raise SystemExit(f"Refusing non-whitelisted licenses: {unknown}")

    summary = collect(
        Path(args.out),
        languages,
        licenses,
        args.min_stars,
        args.max_repos,
        args.max_repo_mb,
        args.token,
        args.sleep,
        args.dry_run,
        repos=repos or None,
        min_size_kb=args.min_size_kb,
        min_records_per_repo=args.min_records_per_repo,
        workers=args.workers,
        fresh=args.fresh,
    )
    print(json.dumps(summary, indent=2))
    if summary["records"] == 0 and summary["already_done"] == 0:
        raise SystemExit(
            "No records collected. Check the token, the repository names and the "
            "connection before running the rest of the pipeline."
        )


if __name__ == "__main__":
    main()
